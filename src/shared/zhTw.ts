interface ZhTwTable {
  s2t: Map<string, string>
  t2s: Map<string, string>
}

function buildTable(): ZhTwTable {
  const s2t = new Map<string, string>()
  const t2s = new Map<string, string>()
  for (const group of PAIRS.split(/\s+/)) {
    const chars = [...group]
    if (chars.length !== 2) continue
    const [s, t] = chars
    if (s === t) continue
    if (!s2t.has(s)) s2t.set(s, t)
    if (!t2s.has(t)) t2s.set(t, s)
  }
  return { s2t, t2s }
}

const TABLE = buildTable()

function convert(text: string, map: Map<string, string>): string {
  const src = String(text ?? '')
  if (!src) return src
  let out = ''
  for (const ch of src) out += map.get(ch) ?? ch
  return out
}

/** 简体 → 繁体（未收录的字原样保留）。 */
export function toTraditional(text: string): string {
  return convert(text, TABLE.s2t)
}

/** 繁体 → 简体（未收录的字原样保留）。 */
export function toSimplified(text: string): string {
  return convert(text, TABLE.t2s)
}

/** 返回「原串 + 另一种写法」，去重（两者相同则只返回原串）。 */
export function zhVariants(text: string): string[] {
  const src = String(text ?? '')
  if (!src) return []
  const out = [src]
  for (const v of [toTraditional(src), toSimplified(src)]) {
    if (v && v !== src && !out.includes(v)) out.push(v)
  }
  return out
}

/** 是否含中文字符（决定要不要做简繁转换 / 中文滑窗切分）。 */
export function hasCjk(text: string): boolean {
  return /[\u4e00-\u9fff]/.test(String(text ?? ''))
}
